const norm = (s) => ` ${(s || '').toLowerCase().replace(/[’`ʼ]/g, "'").replace(/[^\p{L}\p{N}']+/gu, ' ').trim()} `;
const PHRASES = ICONS.flatMap((i) => i.keywords.map((k) => [norm(k), i.id])).sort((a, b) => b[0].length - a[0].length);

/** Іконка за назвою: спершу найдовша ціла фраза зі словника, потім основи слів. */
export function matchIcon(name) {
  const n = norm(name);
  if (n.trim() === '') return null;
  for (const [k, id] of PHRASES) if (n.includes(k)) return id;
  const words = n.trim().split(' ');
  for (const [s, id] of STEMS) if (words.some((w) => w.startsWith(s))) return id;
  return null;
}
